// Static, hand-authored practice questions for the lessons pathway's
// topic lessons (independent of songs). No API call — same questions for
// every user. Organized by subcategory (levels.focus_area), then by topic
// (levels.topics), matching the "levels" table in Supabase. Each topic has 8
// questions split evenly across two axes:
// - category: "grammar" (a structural pattern) or "vocab" (a specific word)
// - mode (implied by type): reading (multiple_choice / fill_blank,
//   recognition) or writing (short_answer, production)
// giving 2 grammar-reading, 2 vocab-reading, 2 grammar-writing, and
// 2 vocab-writing questions per topic.
// Every question also has an `explanation` (the rule behind the answer),
// shown after the learner answers — required here so none can be missed.

export type LessonQuestion = Question & { explanation: string };

export interface TopicLesson {
  lessonId: string;
  levelId: string; // levels.level_id — unique per topic row
  topic: string; // levels.topics
  goal: string; // levels.goal (path box label)
  questions: LessonQuestion[];
}

export interface Subcategory {
  focusArea: string; // levels.focus_area
  levelName: string; // levels.level_name
  topics: TopicLesson[];
}

