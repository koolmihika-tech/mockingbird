"""
Synthesise the audio for the Listening exercise ONCE and store it in the repo.

Reads data/listening/items.json (built by build_items.py), speaks every unique
word/phrase with a Piper es-MX voice, trims the silence, normalises the volume,
encodes a small mono MP3 to assets/listening/<clip>.mp3, and writes the
require() map the app loads (data/listening/clips.ts). Clips that already exist
are skipped, so re-running only synthesises what's new; the app never calls a
TTS service at runtime.

Voice: Piper es_MX-claude-high (Apache-2.0) — free, offline, and OK to
redistribute. (es_MX-ald-medium was tried too, but a recogniser check showed it
garbles isolated words: mean phone score 56 vs 83, with 7 clips scored zero.)
Download it once, inside ml/listening/voices/:

    python -m piper.download_voices es_MX-claude-high

Usage (from the repo root):
    pip install piper-tts lameenc numpy
    python ml/listening/generate_clips.py [--force]
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import wave
from pathlib import Path

import lameenc
import numpy as np
from piper import PiperVoice

ROOT = Path(__file__).resolve().parents[2]
VOICE_DIR = Path(__file__).resolve().parent / "voices"
ITEMS = ROOT / "data" / "listening" / "items.json"
CLIPS_DIR = ROOT / "assets" / "listening"
CLIPS_TS = ROOT / "data" / "listening" / "clips.ts"
VOICES = ["es_MX-claude-high"]

PAD_START_S, PAD_END_S = 0.15, 0.20  # silence around the trimmed speech
SILENCE_FRACTION = 0.02  # samples below 2% of peak count as silence
PEAK = 0.9  # normalise to this peak level
MP3_KBPS = 56


def archived_song_ids() -> set[str]:
    """Songs marked `archived: true` in data/songs.ts: their items and clips stay
    on disk, but the clips are left out of the app bundle."""
    src = (ROOT / "data" / "songs.ts").read_text(encoding="utf-8")
    blocks = re.findall(r"\{\s*\n\s*id: \"\d+\".*?\n  \}", src, flags=re.S)
    return {re.search(r'id: "(\d+)"', b).group(1) for b in blocks if "archived: true" in b}


def voice_for(clip: str) -> str:
    return VOICES[int(hashlib.sha1(clip.encode()).hexdigest(), 16) % len(VOICES)]


def synth(voice: PiperVoice, text: str) -> tuple[np.ndarray, int]:
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        voice.synthesize_wav(text, w)
    buf.seek(0)
    with wave.open(buf, "rb") as w:
        rate = w.getframerate()
        pcm = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16)
    return pcm.astype(np.float32) / 32768.0, rate


def polish(audio: np.ndarray, rate: int) -> np.ndarray:
    peak = float(np.max(np.abs(audio))) or 1.0
    loud = np.flatnonzero(np.abs(audio) > peak * SILENCE_FRACTION)
    if loud.size:
        audio = audio[loud[0] : loud[-1] + 1]
    audio = audio * (PEAK / (float(np.max(np.abs(audio))) or 1.0))
    return np.concatenate([np.zeros(int(PAD_START_S * rate), np.float32), audio, np.zeros(int(PAD_END_S * rate), np.float32)])


def to_mp3(audio: np.ndarray, rate: int) -> bytes:
    enc = lameenc.Encoder()
    enc.set_bit_rate(MP3_KBPS)
    enc.set_in_sample_rate(rate)
    enc.set_channels(1)
    enc.set_quality(2)
    pcm = (np.clip(audio, -1, 1) * 32767).astype(np.int16)
    return bytes(enc.encode(pcm.tobytes()) + enc.flush())


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="re-synthesise existing clips")
    args = ap.parse_args()

    items = json.loads(ITEMS.read_text(encoding="utf-8"))
    texts = {i["clip"]: i["text"] for i in items}
    CLIPS_DIR.mkdir(parents=True, exist_ok=True)

    voices: dict[str, PiperVoice] = {}
    made = 0
    for clip, text in sorted(texts.items()):
        out = CLIPS_DIR / f"{clip}.mp3"
        if out.exists() and not args.force:
            continue
        name = voice_for(clip)
        if name not in voices:
            voices[name] = PiperVoice.load(str(VOICE_DIR / f"{name}.onnx"))
        # Trailing period -> natural falling intonation for an isolated utterance.
        audio, rate = synth(voices[name], f"{text}.")
        out.write_bytes(to_mp3(polish(audio, rate), rate))
        made += 1
        print(f"  {clip}  {name:18} {text}")

    # Only clips an active song uses go in the map: Metro bundles exactly what
    # is require()d, so archived songs' clips stay on disk but out of the app.
    archived = archived_song_ids()
    bundled = {i["clip"] for i in items if i["songId"] not in archived}

    # Metro needs literal require() paths, so the app loads clips from a
    # generated map rather than building filenames at runtime.
    lines = [
        "// Generated by ml/listening/generate_clips.py — do not edit by hand.",
        "// Pre-synthesised es-MX audio for the Listening words/phrases of active songs.",
        "export const LISTENING_CLIPS: Record<string, number> = {",
    ]
    lines += [f'  "{c}": require("../../assets/listening/{c}.mp3"),' for c in sorted(bundled)]
    lines += ["};", ""]
    CLIPS_TS.write_text("\n".join(lines), encoding="utf-8")

    # Drop clips no item uses any more, so the app only ships what it plays.
    for old in CLIPS_DIR.glob("*.mp3"):
        if old.stem not in texts:
            old.unlink()
            print(f"  removed unused {old.name}")

    total = sum(p.stat().st_size for p in CLIPS_DIR.glob("*.mp3"))
    print(f"\n{made} synthesised, {len(texts)} clips total, {total / 1024:.0f} KB -> {CLIPS_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
